#!/usr/bin/env bash
set -euo pipefail

# Generates rspamd/config/worker-controller.inc from RSPAMD_PASSWORD in .env,
# using the rspamd Docker image's own `rspamadm pw` (no local rspamd install
# needed). worker-controller.inc is gitignored - every install must generate
# its own, rather than sharing a committed hash.
#
# Usage: bin/local/hash-rspamd-password.sh
# Re-run whenever RSPAMD_PASSWORD changes, then: docker compose restart rspamd

readonly SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly PROJECT_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
readonly ENV_FILE="${PROJECT_ROOT}/.env"
readonly OUT_FILE="${PROJECT_ROOT}/rspamd/config/worker-controller.inc"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "Error: .env not found at $ENV_FILE" >&2
  echo "Copy .env.example to .env and set RSPAMD_PASSWORD first." >&2
  exit 1
fi

RSPAMD_PASSWORD="$(grep -E '^RSPAMD_PASSWORD=' "$ENV_FILE" | tail -n1 | cut -d= -f2-)"
# Undo the "$$" escaping .env needs for a literal "$" (see .env.example)
RSPAMD_PASSWORD="${RSPAMD_PASSWORD//\$\$/\$}"
if [[ -z "$RSPAMD_PASSWORD" ]]; then
  echo "Error: RSPAMD_PASSWORD is not set in $ENV_FILE" >&2
  exit 1
fi

if ! command -v docker >/dev/null 2>&1; then
  echo "Error: docker is required to run rspamadm (no local rspamd install needed otherwise)" >&2
  exit 1
fi

echo "Hashing RSPAMD_PASSWORD via rspamd/rspamd:latest rspamadm pw..."
HASH="$(docker run --rm rspamd/rspamd:latest rspamadm pw -p "$RSPAMD_PASSWORD")"

cat > "$OUT_FILE" <<EOF
# Generated by bin/local/hash-rspamd-password.sh - do not commit (see .gitignore).
# Regenerate whenever RSPAMD_PASSWORD in .env changes.
password = "${HASH}";
EOF

echo "Wrote ${OUT_FILE}"
echo "Restart rspamd for the new password to take effect: docker compose restart rspamd"
